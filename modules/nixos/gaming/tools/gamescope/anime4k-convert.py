#!/usr/bin/env python3
# Converts an Anime4K mpv user shader (glsl/Upscale/Anime4K_Upscale_CNN_x2_*.glsl)
# into gamescope compute shaders, one per pass: cs_anime4k_<size>_pass<N>.comp.
# Usage: anime4k-convert.py <shader.glsl> <size> <out dir>
import re
import sys
from pathlib import Path

src, size, out = Path(sys.argv[1]), sys.argv[2].lower(), Path(sys.argv[3])
text = src.read_text()

license_block = text[: text.index("//!DESC")].rstrip() + "\n"
chunks = text.split("//!DESC")[1:]

HEAD = """#version 460

#extension GL_GOOGLE_include_directive : require
#extension GL_EXT_scalar_block_layout : require

#include "descriptor_set.h"

layout(
  local_size_x = 8,
  local_size_y = 8,
  local_size_z = 1) in;

layout(binding = 0, scalar)
uniform layers_t {
    uint u_srcWidth;
    uint u_srcHeight;
    uint u_dstWidth;
    uint u_dstHeight;
};

// Convolution outputs go negative, so intermediates are 16-bit float.
layout(binding = 1, rgba16f) writeonly uniform image2D dst_f16;

vec2 g_uv;
"""

MAIN = """
void main()
{
    uvec2 pos = gl_GlobalInvocationID.xy;
    if (pos.x >= u_dstWidth || pos.y >= u_dstHeight)
        return;
    g_uv = (vec2(pos) + 0.5) / vec2(u_dstWidth, u_dstHeight);
%s
}
"""

saved = {"MAIN"}
for n, chunk in enumerate(chunks):
    lines = chunk.splitlines()
    desc = lines[0].strip()
    binds = [l.split()[1] for l in lines if l.startswith("//!BIND")]
    save = next(l.split()[1] for l in lines if l.startswith("//!SAVE"))
    width = next(l.split(None, 1)[1] for l in lines if l.startswith("//!WIDTH"))
    body = "\n".join(l for l in lines[1:] if not l.startswith("//!")).strip()

    # Every bound texture is at the input size; only the last pass doubles it.
    assert all(b in saved for b in binds), f"pass {n} binds an unknown texture"
    assert re.fullmatch(r"\w+\.w( 2 \*)?", width), f"pass {n}: unexpected WIDTH {width}"
    last = save == "MAIN"
    assert last == width.endswith("2 *") and last == (n == len(chunks) - 1)
    saved.add(save)

    macros = []
    for slot, b in enumerate(binds):
        macros += [
            f"#define {b}_tex(p) textureLod(s_samplers[{slot}], (p), 0.0)",
            f"#define {b}_pos g_uv",
            f"#define {b}_size vec2(u_srcWidth, u_srcHeight)",
            f"#define {b}_pt (1.0 / {b}_size)",
            f"#define {b}_texOff(off) {b}_tex({b}_pos + {b}_pt * (off))",
        ]

    if last:
        store = "    imageStore(dst, ivec2(pos), vec4(clamp(hook().rgb, 0.0, 1.0), 1.0));"
    else:
        store = "    imageStore(dst_f16, ivec2(pos), hook());"

    shader = (
        license_block
        + f"\n// Generated by anime4k-convert.py from {src.name}\n// {desc}\n\n"
        + HEAD
        + f"\n// Sampler slots: {', '.join(f'{i} = {b}' for i, b in enumerate(binds))}\n"
        + "\n".join(macros)
        + "\n\n"
        + body
        + "\n"
        + MAIN % store
    )
    (out / f"cs_anime4k_{size}_pass{n}.comp").write_text(shader)
    print(f"pass{n}: binds {binds} -> {save}{' (2x)' if last else ''}")
