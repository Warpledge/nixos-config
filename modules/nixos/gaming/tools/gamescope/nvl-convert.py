#!/usr/bin/env python3
# Converts funnyplanter's NVL upscaler (a pretrained/<size>-NVL.pickle) into gamescope
# compute shaders: nvl_pass<N>.h holds a pass, cs_nvl_pass<N>{,_fp16}.comp wrap it.
# Usage: nvl-convert.py <upstream checkout> <size> <out dir>
# Needs numpy: nix-shell -p 'python3.withPackages (p: [p.numpy])'
import pickle
import re
import sys
from pathlib import Path
from types import SimpleNamespace

repo, size, out = Path(sys.argv[1]), sys.argv[2].lower(), Path(sys.argv[3])
sys.path.insert(0, str(repo))
import common  # noqa: E402
import mpv  # noqa: E402


# The pickle only needs these; anything else would run code on load.
class Unpickler(pickle.Unpickler):
    def find_class(self, mod, name):
        if (mod, name) == ("numpy.core.numeric", "_frombuffer"):
            from numpy._core import numeric

            return numeric._frombuffer
        if (mod, name) in {("collections", "OrderedDict"), ("numpy", "dtype")}:
            return super().find_class(mod, name)
        raise pickle.UnpicklingError(f"refusing {mod}.{name}")


model = repo / "pretrained" / f"{size}-NVL.pickle"
with open(model, "rb") as f:
    m = Unpickler(f).load()
assert m["rgb"] and not m["quant-8"], "only the RGB, non-dp4a models are handled"
args = SimpleNamespace(rgb=True, quant=m["quant"], quant_8=False, size=m.get("size", 0),
                       stem=f"{size}-NVL", name=size, extra=[])
common.init()
_, text = mpv.main(m, args, False)

# Renamed: the first line names the project, the copyright and LGPL text stay.
license_block = text[: text.index("//!DESC")].rstrip() + "\n"
license_block = f"// NVL CNN {size}\n" + license_block.split("\n", 1)[1]
chunks = text.split("//!DESC")[1:]

HEAD ="""#version 460

#extension GL_GOOGLE_include_directive : require
#extension GL_EXT_scalar_block_layout : require
%s
#include "descriptor_set.h"

layout(
  local_size_x = 8,
  local_size_y = 8,
  local_size_z = 1) in;

layout(binding = 0, scalar)
uniform layers_t {
    uint u_srcWidth;
    uint u_srcHeight;
    uint u_dstWidth;
    uint u_dstHeight;
};

%s
#include "nvl_pass%d.h"
"""
FP16 = """#extension GL_EXT_shader_explicit_arithmetic_types_float16 : require
"""
TYPES16 = "f16vec4 f16mat4 float16_t f16mat3x4 f16vec3"
TYPES32 = "vec4 mat4 float mat3x4 vec3"

# Every pass writes a 2x2 block per input pixel; the edge workgroups overrun.
STORE = """
// Intermediates pack 16 channels into 2x2 texels, so they are 16-bit float.
layout(binding = 1, rgba16f) writeonly uniform image2D dst_f16;

void nvl_store(ivec2 p, vec4 v)
{
    if (p.x < int(u_dstWidth) && p.y < int(u_dstHeight))
        imageStore(%s, p, v);
}
"""

scale = {"MAIN": 1}
for n, chunk in enumerate(chunks):
    lines = chunk.splitlines()
    desc = re.sub(r"^\S+", f"NVL-{size}", lines[0].strip())
    binds = [l.split()[1] for l in lines if l.startswith("//!BIND")]
    save = next((l.split()[1] for l in lines if l.startswith("//!SAVE")), None)
    width = next(l.split(None, 1)[1] for l in lines if l.startswith("//!WIDTH"))
    assert re.fullmatch(r"MAIN\.w( \d+ \*)?", width), f"pass {n}: WIDTH {width}"
    assert all(b in scale for b in binds), f"pass {n} binds an unknown texture"
    last = save is None
    assert last == (n == len(chunks) - 1)
    if save:
        scale[save] = int(width.split()[1]) if " " in width else 1

    # Drop the directives and mpv's own fp16 switch; the wrappers pick the types.
    body, skip = [], False
    for l in lines[1:]:
        if l.startswith("//!"):
            continue
        if l.startswith("#extension GL_EXT_shader_explicit_arithmetic"):
            skip = True
        if not skip:
            body.append(l)
        if skip and l.startswith("#endif"):
            skip = False
    body = "\n".join(body).strip()
    body = body.replace("void hook()", "void main()")
    body = body.replace("imageStore(out_image, ", "nvl_store(")

    macros = [
        "#define MAIN_size vec2(u_srcWidth, u_srcHeight)",
        "#define MAIN_pt (1.0 / MAIN_size)",
    ]
    for slot, b in enumerate(binds):
        s = f"s_samplers[{slot}]"
        macros += [
            f"#define {b}_raw {s}",
            f"#define {b}_mul 1.0",
            f"#define {b}_tex(p) textureLod({s}, (p), 0.0)",
            f"#define {b}_gather(p, c) textureGather({s}, (p), (c))",
        ]
        if b != "MAIN":
            macros.append(f"#define {b}_pt (1.0 / (MAIN_size * {scale[b]}.0))")

    header = (
        license_block
        + f"\n// Generated by nvl-convert.py from {model.name}\n// {desc}\n"
        + f"// Sampler slots: {', '.join(f'{i} = {b}' for i, b in enumerate(binds))}\n\n"
        + "\n".join(macros)
        + "\n"
        + STORE % ("dst" if last else "dst_f16")
        + "\n"
        + body
        + "\n"
    )
    (out / f"nvl_pass{n}.h").write_text(header)
    for suffix, ext, types in (("", "", TYPES32), ("_fp16", FP16, TYPES16)):
        defs = "\n".join(f"#define {k} {v}" for k, v in zip("V4 M4 F M3x4 V3".split(), types.split()))
        (out / f"cs_nvl_pass{n}{suffix}.comp").write_text(HEAD % (ext, defs, n))
    print(f"pass{n}: binds {binds} -> {save or 'output'}")
